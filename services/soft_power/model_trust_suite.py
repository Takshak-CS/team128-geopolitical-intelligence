    if preds is None:
        report.add("External benchmark", "soft_power_predictions.csv / master_soft_power_panel.csv", "INFO",
                   "No file with a global_rank column found -- skipped.")
        return

    for cfg in EXTERNAL_BENCHMARKS:
        _run_one_benchmark(report, cfg, preds, source)


