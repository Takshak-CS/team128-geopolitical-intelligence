def _run_one_benchmark(report: Report, cfg: dict, preds: pd.DataFrame, source: str):
    path = ROOT / cfg["file"]
    if not path.exists():
        report.add("External benchmark", cfg["file"], "INFO", "Reference file not found -- skipped.")
        return

    bench = pd.read_csv(path)
    merged = bench.merge(preds[[COUNTRY_COL, "global_rank"]], left_on="iso3", right_on=COUNTRY_COL, how="inner")
    if len(merged) < cfg["min_n"]:
        report.add("External benchmark", cfg["label"], "INFO",
                   f"Only {len(merged)} countries overlap between the model output and this "
                   "reference file -- too few to say anything about correlation.")
        return

    rank_col = cfg["rank_col"]
    corr = merged[["global_rank", rank_col]].corr(method="spearman").iloc[0, 1]

    lines = [
        f"Model ranking source: {source}",
        f"Reference: {cfg['label']}",
        cfg["note"],
        "",
        f"{'iso3':<6}{'country':<24}{'model_rank':>12}{'benchmark_rank':>16}",
    ]
    for _, row in merged.sort_values(rank_col).iterrows():
        lines.append(f"{row['iso3']:<6}{row['country']:<24}{int(row['global_rank']):>12}{int(row[rank_col]):>16}")
    lines.append(f"\nSpearman rank correlation (model vs. {cfg['label']}), n={len(merged)}: {corr:.3f}")

    if corr >= 0.5:
        verdict = "PASS"
        lines.append(
            "\nStrong positive agreement with an independent, differently-constructed index -- "
            "good evidence this dimension of the ranking reflects something real, not just an "
            "artifact of this pipeline's own feature engineering."
        )
    elif corr >= 0.2:
        verdict = "WARN"
        lines.append(
            "\nWeak-to-moderate agreement. Some countries likely rank very differently between "
            "this pipeline and the reference index -- worth spot-checking the biggest "
            "disagreements individually rather than citing either ranking as ground truth."
        )
    else:
        verdict = "FAIL" if corr < 0 else "WARN"
        lines.append(
            "\nLittle to no agreement with this benchmark. If the benchmark measures a "
            "genuinely different construct (see the note above), that alone can explain a low "
            "correlation and isn't necessarily a problem -- but if it claims to measure the same "
            "thing this model does, low agreement is worth investigating before citing either "
            "ranking as authoritative."
        )

    report.add("External benchmark", f"Model rank vs. {cfg['label']}", verdict, "\n".join(lines))


def check_external_benchmark(report: Report):
    report.section("9. External benchmark agreement (four independent country-ranking indices)")

    preds = load_csv("soft_power_predictions.csv")
